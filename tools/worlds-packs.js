#!/usr/bin/env node
"use strict";
// Builds plugins/worlds-brew/js/packs-data.js: the Fantasy kit's models, converted from Kenney's free
// CC0 (public domain) starter kits into Worlds Brew meshes with their colours baked per triangle.
//   git clone --depth 1 https://github.com/KenneyNL/Starter-Kit-City-Builder   (and -3D-Platformer, -Basic-Scene, -Racing)
//   node tools/worlds-packs.js <folder holding those clones>
// The Alien kit is built in code (plugins/worlds-brew/js/alienkit.js) and needs no files.
const fs = require("fs");
const path = require("path");
const M = require("../plugins/worlds-brew/js/models.js");

const SRC = process.argv[2];
if (!SRC) { console.error("usage: node tools/worlds-packs.js <kenney clones folder>"); process.exit(1); }
const ARENA = "Starter-Kit-Basic-Scene/sample/Mini Arena/Models/GLB format/";
// [id, name, file, material, default size, kit]
const FANTASY = [
  ["pine", "Pine tree", ARENA + "tree.glb", "Matte", 1.6, "Mini Arena"],
  ["grove", "Tree grove", "Starter-Kit-City-Builder/models/grass-trees-tall.glb", "Matte", 2, "City Builder"],
  ["forest", "Forest patch", "Starter-Kit-Racing/models/decoration-forest.glb", "Matte", 3, "Racing"],
  ["grass", "Grass tuft", "Starter-Kit-3D-Platformer/models/grass.glb", "Matte", 0.4, "3D Platformer"],
  ["island", "Floating island", "Starter-Kit-3D-Platformer/models/platform-grass-large-round.glb", "Matte", 2.5, "3D Platformer"],
  ["column", "Column", ARENA + "column.glb", "Matte", 1.5, "Mini Arena"],
  ["ruin", "Broken column", ARENA + "column-damaged.glb", "Matte", 1.3, "Mini Arena"],
  ["statue", "Statue", ARENA + "statue.glb", "Matte", 1.4, "Mini Arena"],
  ["wall", "Castle wall", ARENA + "wall.glb", "Matte", 1.6, "Mini Arena"],
  ["corner", "Wall corner", ARENA + "wall-corner.glb", "Matte", 1.6, "Mini Arena"],
  ["gate", "Castle gate", ARENA + "wall-gate.glb", "Matte", 1.8, "Mini Arena"],
  ["banner", "Banner", ARENA + "banner.glb", "Matte", 1.2, "Mini Arena"],
  ["stairs", "Stone stairs", ARENA + "stairs.glb", "Matte", 1, "Mini Arena"],
  ["house", "Cottage", "Starter-Kit-City-Builder/models/building-small-a.glb", "Matte", 1.8, "City Builder"],
  ["house2", "Town house", "Starter-Kit-City-Builder/models/building-small-c.glb", "Matte", 1.8, "City Builder"],
  ["fountain", "Fountain", "Starter-Kit-City-Builder/models/pavement-fountain.glb", "Matte", 1.6, "City Builder"],
  ["tents", "Camp tents", "Starter-Kit-Racing/models/decoration-tents.glb", "Matte", 3, "Racing"],
  ["flag", "Flag", "Starter-Kit-3D-Platformer/models/flag.glb", "Matte", 1, "3D Platformer"]
];

const out = FANTASY.map(([id, name, file, mat, size, kit]) => {
  const f = path.join(SRC, file), b = fs.readFileSync(f);
  const m = M.parseGLB(b.buffer.slice(b.byteOffset, b.byteOffset + b.length), name, { image: (u) => fs.readFileSync(path.join(path.dirname(f), u)) });
  if (!m.tc) throw new Error(file + ": no colours read");
  console.log(name.padEnd(16), String(m.tris).padStart(5), "triangles");
  return { id: "fantasy/" + id, name, mat, size, credit: "Kenney (kenney.nl), " + kit + " kit, CC0", mesh: M.meshToJSON(m) };
});
const js = "\"use strict\";\n// Generated by tools/worlds-packs.js from Kenney's CC0 starter kits (kenney.nl). Do not edit by hand.\n" +
  "module.exports = { fantasy: " + JSON.stringify(out) + " };\n";
const dst = path.join(__dirname, "..", "plugins", "worlds-brew", "js", "packs-data.js");
fs.writeFileSync(dst, js);
console.log("wrote", path.relative(process.cwd(), dst), Math.round(js.length / 1024) + " KB");
