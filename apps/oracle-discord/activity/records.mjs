const CHAMBER = ["ember-menu", "pixel-and-pennywhistle", "arcade-groove", "the-occurrence", "the-cults-secret", "dreamy-game-over", "high-score-hero", "arcade-heros-theme",
  "the-curiosity-shop", "nile-arcade-dreams", "dont-judge-a-space-kid", "the-nordic-trading-post", "coin-drop-groove", "arcade-alley", "jade-cartridge-shop", "pixel-shaman"];

export function parse(tsv) {
  const [head, ...rows] = tsv.trim().split(/\r?\n/), cols = head.split("\t");
  const unq = (v) => (/^".*"$/.test(v) ? v.slice(1, -1).replace(/""/g, '"') : v); // spreadsheet-style quoting
  return rows.map((l) => Object.fromEntries(l.split("\t").map((v, i) => [cols[i], unq(v.trim())])));
}
/** What the credit says: blank when none is needed and none was given; "Not required" lines are dropped. */
const creditOf = (r) => { const c = CREDIT[r.title] || CREDIT[r.pack] || r.credit || ""; return /^not required|^no need|^copyright\/attribution notice:?$/i.test(c) ? "" : c.replace(/&amp;/g, "&"); };

export function records(rows, hasFile = () => true) {
  return rows.map((r) => {
    const id = SAME_AS[r.id] || r.id, live = CHAMBER.includes(id);
    return { id, title: TITLE[r.title] || r.title.replace(/ \((full song|credits song)\)$/, "").replace(/^(Lights Down) (Hands)/, "$1, $2").replace(/-/g, r.pack.includes("McLean") ? " " : "-"),
      house: r.brand, role: r.role === "hidden" ? "hidden" : "record", from: r.from || "", opener: /^y/i.test(r.opener || ""), live,
      licence: r.licence || (r.source === "download" ? "" : "Original"), credit: creditOf(r), pack: (r.pack || "").replace(/&amp;/g, "&") };
  }).filter((r) => r.live || hasFile(r.id));
}

export function writeRecords() {
  const rows = parse(readFileSync(new URL("music/house-records.tsv", here), "utf8"));
  const out = records(rows, (id) => existsSync(new URL(`music/${id}.mp3`, here)));
  writeFileSync(new URL("src/hosts/house-records.gen.js", here), `// Generated by activity/records.mjs from music/house-records.tsv (the brand map). Don't edit by hand.\nexport const RECORDS = ${JSON.stringify(out, null, 0).replace(/\},\{/g, "},\n  {")};\n`);
  console.log(`house-records.gen.js: ${out.length} of ${rows.length} records (${rows.length - out.length} without audio)`);
}
if (import.meta.url === `file://${process.argv[1]}`) writeRecords();
