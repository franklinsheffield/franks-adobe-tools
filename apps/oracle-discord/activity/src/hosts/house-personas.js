const pick = (pool, used = []) => {
  if (!pool || !pool.length) return null;
  let fresh = pool.filter((l) => !used.includes(l)); if (!fresh.length) { for (const l of pool) { const i = used.indexOf(l); if (i >= 0) used.splice(i, 1); } fresh = pool; }
  const l = fresh[Math.floor(Math.random() * fresh.length)]; used.push(l); return l;
};
/** The chosen personality's line about this House ("greet" | "joke"), or null (the Oracle's Chamber, or the classic mystic). */
export function housePersonaLine(personaId, houseId, kind, name = "traveller", used = []) {
  const l = pick((((HOUSE_PERSONAS[personaId] || {})[houseId]) || {})[kind], used); return l ? l.replace(/\{name\}/g, name) : null;
}
