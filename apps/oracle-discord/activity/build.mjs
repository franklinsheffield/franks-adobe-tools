// Builds the Oracle Chamber Activity into activity/dist: bundles the live reading modules for the browser
// (resvg, node:fs and node:url swapped for small shims), inlines their image assets and copies the fonts.
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, existsSync } from "node:fs";
import { MODULES } from "../src/registry.js";

const here = new URL("./", import.meta.url), app = new URL("../", here), dist = new URL("dist/", here);
mkdirSync(new URL("assets/", dist), { recursive: true });

import { writeRecords } from "./records.mjs";
writeRecords(); // the House records list (src/hosts/house-records.gen.js) from music/house-records.tsv
// Every module currently registered, so new systems arrive with the next deploy.
writeFileSync(new URL("src/modules.gen.js", here), `// Generated by build.mjs from src/registry.js MODULES.\n${MODULES.map((m, i) => `import * as m${i} from "../../src/modules/${m}/index.js";`).join("\n")}\nexport const MODS = { ${MODULES.map((m, i) => `${JSON.stringify(m)}: m${i}`).join(", ")} };\n`);

// Image assets the modules read with readFileSync (by file name).
const assets = {};
const scan = (dir) => { if (!existsSync(dir)) return; for (const e of readdirSync(dir, { withFileTypes: true })) {
  const u = new URL(e.name + (e.isDirectory() ? "/" : ""), dir);
  if (e.isDirectory()) { if (e.name !== "node_modules") scan(u); } else if (/\.(png|jpg)$/i.test(e.name)) assets[e.name] = readFileSync(u).toString("base64");
} };
scan(new URL("src/", app)); scan(new URL("assets/", app));
writeFileSync(new URL("src/assets.gen.js", here), `// Generated by build.mjs: image assets the reading modules load, by file name.\nexport const ASSETS = ${JSON.stringify(assets)};\n`);

const shim = (f) => new URL(`src/shims/${f}`, here).pathname;
await build({
  entryPoints: [new URL("src/main.js", here).pathname], bundle: true, format: "esm", target: "es2022", minify: true,
  outfile: new URL("chamber.js", dist).pathname, platform: "browser", logLevel: "warning",
  alias: { "@resvg/resvg-js": shim("resvg.js"), "node:fs": shim("fs.js"), "node:url": shim("url.js"), fs: shim("fs.js") },
  define: { "process.env.NODE_ENV": '"production"' },
});
for (const f of ["index.html", "chamber.css"]) copyFileSync(new URL("src/" + f, here), new URL(f, dist));
for (const f of ["Cinzel-Regular.otf", "Cinzel-Black.otf"]) if (existsSync(new URL("fonts/" + f, app))) copyFileSync(new URL("fonts/" + f, app), new URL("assets/" + f, dist));
for (const f of ["DejaVuSans.ttf", "DejaVuSans-Bold.ttf", "NotoSansEgyptianHieroglyphs-Subset.ttf", "NotoSansRunic-Subset.ttf", "NotoSerifSC-Subset.ttf"]) copyFileSync(new URL("assets/fonts/" + f, app), new URL("assets/" + f, dist));
copyFileSync(new URL("assets/oracle.png", app), new URL("assets/oracle.png", dist));
// Vibe fonts (SIL Open Font License, from Fontsource), latin subsets.
for (const f of readdirSync(new URL("src/fonts/", here))) if (f.endsWith(".woff2")) copyFileSync(new URL("src/fonts/" + f, here), new URL("assets/" + f, dist));
// Music (Frank's soundtracks, music.js): served as static files beside the page.
mkdirSync(new URL("music/", dist), { recursive: true });
for (const f of readdirSync(new URL("music/", here))) if (f.endsWith(".mp3")) copyFileSync(new URL("music/" + f, here), new URL("music/" + f, dist));
console.log("Oracle Chamber built:", MODULES.join(", "));
