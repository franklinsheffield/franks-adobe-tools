# Builds activity/src/inscriptions/fonts.gen.js: OFL Noto subsets holding exactly the characters of the Inscription
# Tray samples, as base64 woff2. Usage: python3 -I scripts/gen-inscription-fonts.py <dir of @fontsource/noto-* .tgz>
# (npm pack @fontsource/noto-sans-<script> for each package in PKG). Needs fonttools + brotli. Licence:
# assets/fonts/NOTO-LICENSE.txt (SIL OFL 1.1).
import base64, io, json, os, re, subprocess, sys, tarfile
from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "activity", "src", "inscriptions", "data.js")
OUT = os.path.join(HERE, "..", "activity", "src", "inscriptions", "fonts.gen.js")
PKG = {"hebrew": "noto-sans-hebrew", "arabic": "noto-sans-arabic", "devanagari": "noto-sans-devanagari", "runic": "noto-sans-runic",
  "egyptian": "noto-sans-egyptian-hieroglyphs", "cuneiform": "noto-sans-cuneiform", "ogham": "noto-sans-ogham", "cherokee": "noto-sans-cherokee",
  "georgian": "noto-sans-georgian", "armenian": "noto-sans-armenian", "ethiopic": "noto-sans-ethiopic", "thai": "noto-sans-thai",
  "tibetan": "noto-serif-tibetan", "mongolian": "noto-sans-mongolian", "gothic": "noto-sans-gothic", "coptic": "noto-sans-coptic",
  "glagolitic": "noto-sans-glagolitic", "phoenician": "noto-sans-phoenician", "tifinagh": "noto-sans-tifinagh", "linearb": "noto-sans-linear-b",
  "oldpersian": "noto-sans-old-persian", "ugaritic": "noto-sans-ugaritic", "brahmi": "noto-sans-brahmi", "olditalic": "noto-sans-old-italic",
  "syriac": "noto-sans-syriac", "nko": "noto-sans-nko", "vai": "noto-sans-vai", "lineara": "noto-sans-linear-a"}

src = sys.argv[1]
js = subprocess.run(["node", "--input-type=module", "-e", f"import('{DATA}').then(m=>console.log(JSON.stringify(m.SCRIPTS.filter(s=>s.font).map(s=>[s.font,s.sample]))))"], capture_output=True, text=True, check=True).stdout
text = {}
for k, s in json.loads(js): text[k] = text.get(k, "") + s
out = {}
for key, chars in sorted(text.items()):
    pkg = PKG[key]; tgz = next(f for f in os.listdir(src) if f.startswith("fontsource-" + pkg + "-"))
    cps = {ord(c) for c in chars if not c.isspace()}
    best = None
    with tarfile.open(os.path.join(src, tgz)) as t:
        for m in t.getmembers():
            if not re.search(r"-400-normal\.woff2$", m.name) or re.search(r"(latin|greek|cyrillic|vietnamese|math|symbols)", m.name.split("/")[-1].replace(pkg, "")): continue
            f = TTFont(io.BytesIO(t.extractfile(m).read())); cmap = f.getBestCmap() or {}
            have = len(cps & set(cmap))
            if not best or have > best[0]: best = (have, f)
    assert best and best[0] == len(cps), f"{key}: font misses {len(cps) - (best[0] if best else 0)} characters"
    opts = subset.Options(); opts.flavor = "woff2"; opts.layout_features = ["*"]; opts.name_IDs = ["*"]; opts.notdef_outline = True
    sub = subset.Subsetter(opts); sub.populate(text=chars); sub.subset(best[1])
    buf = io.BytesIO(); best[1].flavor = "woff2"; best[1].save(buf); out[key] = base64.b64encode(buf.getvalue()).decode()
with open(OUT, "w") as fh:
    fh.write("// Generated by scripts/gen-inscription-fonts.py: OFL Noto subsets (only the Inscription Tray sample characters), as\n// base64 woff2. Licence: assets/fonts/NOTO-LICENSE.txt. Do not edit by hand.\n")
    fh.write("export const FONTS = " + json.dumps(out) + ";\n")
print({k: len(v) for k, v in out.items()}, sum(len(v) for v in out.values()))
