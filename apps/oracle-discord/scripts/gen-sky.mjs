// Generates activity/src/stars/sky.gen.js for the Star Lore Navigator room: real star positions (Hipparcos, J2000),
// magnitudes and B-V colours from d3-celestial's data (BSD-3-Clause, (c) 2015 Olaf Frohn), the 88 IAU stick figures,
// and each star's IAU constellation from astronomy-engine's official boundaries.
//   npm pack d3-celestial@0.7.35 && tar xzf d3-celestial-0.7.35.tgz
//   node scripts/gen-sky.mjs path/to/package/data
import { readFileSync, writeFileSync } from "node:fs";
import { Constellation } from "astronomy-engine";

const dir = process.argv[2]; if (!dir) throw new Error("usage: node scripts/gen-sky.mjs <d3-celestial data dir>");
const J = (f) => JSON.parse(readFileSync(dir + "/" + f, "utf8"));
const LIMIT = 4.6, EXTRA = new Set([17489, 17851, 17499, 17531, 17573, 17608, 17702, 17847]); // all the Pleiades sisters
const r2 = (x) => Math.round(x * 100) / 100, ra = (lon) => r2(((lon % 360) + 360) % 360);
// Every star the stick figures use is kept too (some are fainter than LIMIT), so each figure can be drawn star to star.
const all = J("stars.6.json").features, figLines = J("constellations.lines.json").features;
const near = (lo, la) => { let b = null, bd = 0.2; for (const f of all) { const [x, y] = f.geometry.coordinates;
  const d = Math.hypot(((((x - lo) % 360) + 540) % 360 - 180) * Math.cos((la * Math.PI) / 180), y - la); if (d < bd) { bd = d; b = f; } } return b; };
const FIG = {};
for (const f of figLines) { const e = new Set(); for (const l of f.geometry.coordinates) for (let i = 1; i < l.length; i++) {
  const a = near(...l[i - 1]), b = near(...l[i]); if (!a || !b || a.id === b.id) continue; EXTRA.add(a.id); EXTRA.add(b.id); e.add([a.id, b.id].sort((x, y) => x - y).join("-")); }
  FIG[f.id] = [...e].map((k) => k.split("-").map(Number)); }
const stars = all.filter((f) => f.properties.mag <= LIMIT || EXTRA.has(f.id)).map((f) => {
  const [lon, lat] = f.geometry.coordinates, R = ra(lon);
  return [R, r2(lat), r2(f.properties.mag), r2(+f.properties.bv || 0), f.id, Constellation(R / 15, lat).symbol];
}).sort((a, b) => a[2] - b[2]);
// The photo-real sky (level 3) adds every star to magnitude 6 and the Milky Way's five brightness levels.
const r1 = (x) => Math.round(x * 10) / 10, ids = new Set(stars.map((s) => s[4]));
const faint = all.filter((f) => !ids.has(f.id)).map((f) => [r1(ra(f.geometry.coordinates[0])), r1(f.geometry.coordinates[1]), r1(f.properties.mag), r1(+f.properties.bv || 0)]);
const mw = J("mw.json").features.map((f) => f.geometry.coordinates.flatMap((poly) => poly.map((ring) => {
  const out = []; let last = null;
  for (const [lo, la] of ring) { const p = [r1(ra(lo)), r1(la)]; if (!last || Math.hypot(p[0] - last[0], p[1] - last[1]) >= 0.8) { out.push(p); last = p; } }
  return out; }).filter((r) => r.length > 3)));
const lines = {}; for (const f of J("constellations.lines.json").features) lines[f.id] = f.geometry.coordinates.map((l) => l.map(([lo, la]) => [ra(lo), r2(la)]));
const names = {}; for (const f of J("constellations.json").features) names[f.id] = f.properties.name;
const sn = J("starnames.json"), starNames = {};
for (const s of stars) { const n = sn[s[4]]; if (n && n.name) starNames[s[4]] = n.name; }
const out = `// Generated by scripts/gen-sky.mjs. Star data: Hipparcos via d3-celestial (BSD-3-Clause, (c) 2015 Olaf Frohn).
// STARS: [RA deg J2000, Dec deg, magnitude, B-V colour, HIP number, IAU constellation]; LINES: stick figures (RA, Dec);\n// FAINT: [RA, Dec, mag, B-V] for the rest of the stars to magnitude 6; MILKY_WAY: 5 brightness levels of rings [RA, Dec].\n// FIGURES: the same stick figures as star-to-star edges [HIP, HIP] (every figure star is in STARS).
export const STARS = ${JSON.stringify(stars)};
export const LINES = ${JSON.stringify(lines)};
export const FIGURES = ${JSON.stringify(FIG)};
export const FAINT = ${JSON.stringify(faint)};
export const MILKY_WAY = ${JSON.stringify(mw)};
export const CON_NAMES = ${JSON.stringify(names)};
export const STAR_NAMES = ${JSON.stringify(starNames)};
`;
writeFileSync(new URL("../activity/src/stars/sky.gen.js", import.meta.url), out);
console.log(stars.length, "stars,", Object.keys(lines).length, "figures,", (out.length / 1024).toFixed(0), "KB");
