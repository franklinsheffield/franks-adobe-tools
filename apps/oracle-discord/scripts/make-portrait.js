// Renders the Oracle portrait PNG (assets/oracle.png) and the Worker's embedded copy (src/oracle/portrait.js).
// Run after changing src/oracle/figure.js: node scripts/make-portrait.js
import { writeFileSync } from "node:fs";
import { Resvg } from "@resvg/resvg-js";
import { portraitSvg } from "../src/oracle/figure.js";
const png = new Resvg(portraitSvg(256)).render().asPng();
writeFileSync(new URL("../assets/oracle.png", import.meta.url), png);
writeFileSync(new URL("../src/oracle/portrait.js", import.meta.url),
  `// Generated by scripts/make-portrait.js: the Oracle portrait (256 px PNG) served by the Worker at /oracle.png.\nexport const PORTRAIT_PNG_B64 = "${Buffer.from(png).toString("base64")}";\n`);
console.log("oracle.png", png.length, "bytes");
