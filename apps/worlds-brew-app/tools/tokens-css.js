#!/usr/bin/env node
"use strict";
// Builds renderer/tokens.css from the suite's design tokens (tokens/brew-tokens.json, W3C DTCG), so the app uses the
// same colours, fonts and sizes as the Photoshop panels and After Effects effects. Run by tools/sync-engine.js.
const fs = require("fs"), path = require("path");
const APP = path.resolve(__dirname, ".."), SRC = path.resolve(APP, "../../tokens/brew-tokens.json"), OUT = path.join(APP, "renderer/tokens.css");
const TOOL = "worlds-brew";
// sRGB hex -> OKLCH (Björn Ottosson's OKLab)
function oklch(hex) {
  const lin = (c) => (c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4));
  const [r, g, b] = [1, 3, 5].map((i) => lin(parseInt(hex.slice(i, i + 2), 16) / 255));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b), m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b), s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s, A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s, B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
  let h = Math.atan2(B, A) * 180 / Math.PI; if (h < 0) h += 360;
  return [L, Math.hypot(A, B), h];
}
function build() {
  const T = JSON.parse(fs.readFileSync(SRC, "utf8")), C = T.color;
  const hex = (t) => t.$value.hex, rgba = (t) => { const c = t.$value.components.map((v) => Math.round(v * 255)); return t.$value.alpha != null ? "rgba(" + c.join(", ") + ", " + t.$value.alpha + ")" : t.$value.hex; };
  const px = (t) => t.$value.value + t.$value.unit, ms = (t) => t.$value.value + t.$value.unit, fam = (t) => t.$value.map((f) => (/\s/.test(f) ? '"' + f + '"' : f)).join(", ");
  const glow = hex(C.glow[TOOL]), [L, Ch, H] = oklch(glow);
  const lines = [
    "/* Generated by tools/tokens-css.js from tokens/brew-tokens.json (the suite's shared design tokens). Do not edit: change the JSON. */",
    ":root {",
    "  --tk-ink: " + hex(C.ink) + "; --tk-stroke: " + rgba(C.stroke) + "; --tk-soft: " + rgba(C.soft) + "; --tk-select: " + hex(C.select) + ";",
    "  --tk-led-busy: " + hex(C.led.busy) + "; --tk-led-error: " + hex(C.led.error) + "; --tk-error-text: " + hex(C.errorText) + ";",
    "  --tk-glow-hex: " + glow + ";   /* color.glow." + TOOL + " */",
    "  --mint-l: " + L.toFixed(3) + "; --mint-c: " + Ch.toFixed(3) + "; --mint-h: " + H.toFixed(1) + ";",
    "  --tk-font-display: " + fam(T.font.display) + "; --tk-font-ui: " + fam(T.font.ui) + ";",
    "  --tk-target-min: " + px(T.size.targetMin) + "; --tk-knob: " + px(T.size.knob) + "; --tk-value-box: " + px(T.size.valueBox) + "; --tk-radius: " + px(T.size.radius) + ";",
    "  --tk-micro: " + ms(T.duration.micro) + ";",
    "}",
    ""
  ];
  return lines.join("\n");
}
function sync(check) { const css = build(), same = fs.existsSync(OUT) && fs.readFileSync(OUT, "utf8") === css; if (!same && !check) fs.writeFileSync(OUT, css); return same ? [] : ["tokens.css"]; }
if (require.main === module) console.log(sync(false).length ? "wrote renderer/tokens.css" : "tokens.css up to date");
module.exports = { sync, build, oklch };
