#!/usr/bin/env node
"use strict";
// Builds the Pixel Scape web version into web/dist/ from the same renderer + engine code as the desktop app.
//   node web/build.js          (run `npm run sync` first so engine/ is current)
// The renderer loads Node modules with window.require("<id>"); this script finds every id the renderer uses and
// bundles them into one map, so the web host can answer window.require from the bundle.
const fs = require("fs"), path = require("path"), esbuild = require("esbuild");
const APP = path.resolve(__dirname, ".."), WEB = __dirname, OUT = path.join(WEB, "dist");
const SH = (f) => path.join(WEB, "shims", f);
const NODE = { electron: SH("electron.js"), fs: SH("vfs.js"), url: SH("url.js"), buffer: "buffer", path: "path-browserify" };

function registry() {
  const ids = new Set(Object.keys(NODE));
  for (const f of fs.readdirSync(path.join(APP, "renderer"))) if (f.endsWith(".js"))
    for (const m of fs.readFileSync(path.join(APP, "renderer", f), "utf8").matchAll(/\b(?:req|window\.require)\(\s*"([^"]+)"\s*\)/g)) ids.add(m[1]);
  const rel = (p) => "./" + path.relative(path.join(WEB, ".gen"), p).split(path.sep).join("/");
  const lines = [...ids].sort().map((id) => {
    const target = NODE[id] ? (NODE[id].startsWith("/") ? rel(NODE[id]) : NODE[id]) : rel(path.join(APP, "renderer", id));
    return `  ${JSON.stringify(id)}: () => require(${JSON.stringify(target)})`;
  });
  fs.mkdirSync(path.join(WEB, ".gen"), { recursive: true });
  fs.writeFileSync(path.join(WEB, ".gen", "registry.js"), "// generated by web/build.js\nmodule.exports = {\n" + lines.join(",\n") + "\n};\n");
  return ids.size;
}

async function build() {
  const n = registry();
  fs.rmSync(OUT, { recursive: true, force: true }); fs.mkdirSync(OUT, { recursive: true });
  const r = await esbuild.build({
    entryPoints: [path.join(WEB, "entry.js")], bundle: true, format: "esm", target: "es2022", outfile: path.join(OUT, "app.js"),
    minify: process.argv.includes("--minify"), sourcemap: true, logLevel: "warning", metafile: true,
    alias: { fs: SH("vfs.js"), zlib: SH("zlib.js"), crypto: SH("crypto.js"), path: "path-browserify", url: SH("url.js"), electron: SH("electron.js"),
      "three/addons/controls/TransformControls.js": path.join(APP, "renderer/vendor/TransformControls.js") },
    inject: [SH("buffer-global.js")], define: { "process.env": "{}", "process.platform": '"web"' }
  });
  // styles: the same three sheets the desktop window loads, plus the web host's own
  const css = ["engine/kit/panel.css", "renderer/tokens.css", "renderer/app.css"].map((f) => fs.readFileSync(path.join(APP, f), "utf8")).join("\n") + "\n" + fs.readFileSync(path.join(WEB, "web.css"), "utf8");
  fs.writeFileSync(path.join(OUT, "app.css"), css);
  fs.copyFileSync(path.join(WEB, "index.html"), path.join(OUT, "index.html"));
  fs.copyFileSync(path.join(APP, "build/icon.png"), path.join(OUT, "icon.png"));
  const size = fs.statSync(path.join(OUT, "app.js")).size;
  console.log(`web build: ${n} modules mapped, app.js ${(size / 1e6).toFixed(2)} MB -> ${path.relative(process.cwd(), OUT)}`);
  return r;
}
if (require.main === module) build().catch((e) => { console.error(e); process.exit(1); });
module.exports = { build };
