"use strict";
// Writes ae/effects/<tool>/<ns>_presets.h from the Photoshop looks (plugins/<tool>/js/state.js),
// so the AE effect always ships the same looks. Run after any look change:
//   node ae/tools/gen-presets.js            (all wave-2 tools)
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..", "..");
const toText = require("../tests/params-text.js");
const TOOLS = { mobglow: "mob", depthtone: "dt", decompressor: "dc", chrometone: "ct" };
const esc = (s) => JSON.stringify(s);
for (const [tool, ns] of Object.entries(TOOLS)) {
  const { DEFAULTS, PRESETS, merge } = require(path.join(root, `plugins/${tool}/js/state.js`));
  let out = `// GENERATED by ae/tools/gen-presets.js from plugins/${tool}/js/state.js - do not edit\n#pragma once\nnamespace ${ns} {\nstruct Look { const char* cat; const char* name; const char* text; };\nstatic const Look LOOKS[] = {\n`;
  for (const p of PRESETS) out += `  { ${esc(p.cat)}, ${esc(p.name)}, ${esc(toText(merge(DEFAULTS, p.p)))} },\n`;
  out += `};\nstatic const int LOOK_COUNT = ${PRESETS.length};\n}\n`;
  fs.writeFileSync(path.join(__dirname, "..", `effects/${tool}/${ns}_presets.h`), out);
  console.log(tool, "wrote", PRESETS.length, "looks");
}
