#!/usr/bin/env node
"use strict";
// Copies the Photoshop Labs' 3.0 hover help (shared/help.js) into the AE Lab Console as a
// plain browser script (window.LabHelp), so both hosts share one implementation.
//   node ae/tools/gen-console-help.js
const fs = require("fs"), path = require("path");
const src = fs.readFileSync(path.join(__dirname, "../../shared/help.js"), "utf8");
const out = "// GENERATED by ae/tools/gen-console-help.js from shared/help.js - do not edit.\n" +
  "(function () {\nvar module = { exports: {} };\n" + src + "\nwindow.LabHelp = module.exports;\n})();\n";
fs.writeFileSync(path.join(__dirname, "../console/js/help.js"), out);
console.log("wrote ae/console/js/help.js");
