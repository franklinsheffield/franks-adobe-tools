"use strict";
// Writes ae/effects/crt-phaser/crt_presets.h from the Photoshop looks (plugins/crt-phaser/js/state.js),
// so the AE effect always ships the same looks. Run after any look change.
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..", "..");
const { DEFAULTS, PRESETS, merge } = require(path.join(root, "plugins/crt-phaser/js/state.js"));
const toText = require("../tests/crt-params-text.js");
const esc = (s) => JSON.stringify(s);
let out = "// GENERATED by ae/tools/gen-crt-presets.js from plugins/crt-phaser/js/state.js - do not edit\n#pragma once\nnamespace crt {\nstruct Look { const char* cat; const char* name; const char* text; };\nstatic const Look LOOKS[] = {\n";
for (const p of PRESETS) out += `  { ${esc(p.cat)}, ${esc(p.name)}, ${esc(toText(merge(DEFAULTS, p.p)))} },\n`;
out += `};\nstatic const int LOOK_COUNT = ${PRESETS.length};\n}\n`;
fs.writeFileSync(path.join(__dirname, "..", "effects/crt-phaser/crt_presets.h"), out);
console.log("wrote", PRESETS.length, "looks");
